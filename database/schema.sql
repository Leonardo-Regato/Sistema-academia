
CREATE TABLE alunos (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome VARCHAR,
    data_nascimento DATE
);

CREATE TABLE professores (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome VARCHAR,
    data_nascimento DATE
);

CREATE TABLE usuarios (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome_usuario VARCHAR NOT NULL UNIQUE,
    senha_hash VARCHAR NOT NULL
);
